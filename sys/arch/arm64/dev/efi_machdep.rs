//! efi(4) on arm64: the UEFI runtime services, mapped into a pmap of their own, and the
//! time-of-day clock they provide (`GetTime`/`SetTime`). Under QEMU with EDK2 this is the
//! machine's clock: the firmware keeps the PL031 for itself and disables its device-tree node,
//! so plrtc(4) does not attach.
//!
//! Upstream: sys/arch/arm64/dev/efi_machdep.c @ 3ce1f3f79392
//!
//! ## Deviations
//! - The system table's address and the memory map come from the boot protocol through
//!   `machdep.rs` (`SYSTEM_TABLE`, `efi_mmap`, `MMAP_DESC_SIZE`) instead of efiboot's
//!   `openbsd,uefi-*` properties in `/chosen`.
//! - `efi_enter_check` (a `setjmp` on `efi_jmpbuf`) and the runtime-service call that follows
//!   it are `efi_call`: an assembly trampoline (`efi_rs_call`) saves the callee-saved
//!   registers, the stack pointer and the return address in `efi_jmpbuf`, loads the service
//!   from its slot of the runtime services table (so that load is covered too, as in C) and
//!   calls it; `efi_fault`, the `pcb_onfault` target, restores them and returns "faulted",
//!   which `efi_call` turns into `efi_leave` and `EFAULT`. A fault outside such a call (the
//!   `FirmwareVendor` and configuration-table reads of `efi_attach`) returns through
//!   whatever `efi_jmpbuf` holds, as the C's `longjmp` does.
//! - `pmap_create` makes a three-level pmap and the C then sets `have_4_level_pt`, so the
//!   union `pm_vp` reads the same table as level 0; here `pm_vp` is an enum
//!   (`include/pmap.rs`, deviations), switched to `PmVp::L0` over the same table.
//! - The chip handle is `malloc`ed (`include/efivar.rs`, deviations).
//! - `efi_cd` (generated by `config(8)` in C, used by `dev/efi/efi.c`) is defined here.
//! - The `smbios` attach arguments carry the parent's node, DMA tag and cells where the C
//!   leaves them uninitialised; no smbios(4) driver is configured.
//! - A memory map without a descriptor size maps nothing (the C would divide by zero).

