//! HMAC (RFC 2104) over MD5, SHA-1 and SHA-256, with the hash's state kept in the context
//! so that a message can be fed in pieces. (IPsec's `HMAC-*-96` does not use this file: the
//! software crypto driver precomputes the inner and outer states itself, see `cryptosoft.c`.)
//!
//! Upstream: sys/crypto/hmac.h @ 3ce1f3f79392, sys/crypto/hmac.c @ 3ce1f3f79392
//! LZ: sys/crypto/hmac.rs@f5985f1d055a
//!
//! ## Deviations
//! - The header and the file share this module; the contexts are [`HmacMd5Ctx`],
//!   [`HmacSha1Ctx`] and [`HmacSha256Ctx`].
//! - The three families are one `macro_rules!` expansion each, so the three bodies, identical
//!   but for the hash, are written once.
//!
//! ## Redesign
//! - Each context and its three functions are a type with methods (`docs/IDIOMS.md`, "a hash
//!   context"): `HMAC_*_Init(ctx, key, key_len)` is `new(key)`, `HMAC_*_Update` is `update`
//!   over a slice, and `HMAC_*_Final(digest, ctx)` is `finalize`, which returns the MAC. The
//!   old names were generated by the macro in LZ too, so no lineage row records them: they
//!   are `HmacMd5Ctx::new` .. `HmacSha256Ctx::finalize` here.
//! - The macro takes the hash's context type and calls its methods (`new`, `update`,
//!   `finalize`) instead of being handed the hash's three C functions.
//! - The fields are private; `key_len` is a `usize`, so the copies of the key need no casts.
//! - Wiping: `k_ipad` and `k_opad` are wiped with `explicit_bzero` as in the C. In addition
//!   `finalize` wipes the inner digest, the hashed long key, and the whole context (the key
//!   the C leaves in it after `HMAC_*_Final`): more than the C wipes, never less, and no
//!   output changes.

use libkern::explicit_bzero;

use super::md5::{MD5_BLOCK_LENGTH, MD5_DIGEST_LENGTH, Md5Ctx};
use super::sha1::{SHA1_BLOCK_LENGTH, SHA1_DIGEST_LENGTH, Sha1Ctx};
use super::sha2::{SHA256_BLOCK_LENGTH, SHA256_DIGEST_LENGTH, Sha256Ctx};
use super::wipe;

/// Defines one HMAC family: the context type over a hash given by its context type and its
/// block and digest lengths, with `new`, `update` and `finalize`.
macro_rules! hmac_family {
    ($ctx_ty:ident, $hash_ctx:ty, $block:ident, $digest:ident, $name:literal) => {
        #[doc = concat!("`", $name, "`: an HMAC in progress, from `new(key)` to `finalize`.")]
        ///
        /// `Default` is the wiped, all-zero context, not an HMAC under any key.
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        pub struct $ctx_ty {
            /// `ctx`: the inner hash.
            ctx: $hash_ctx,
            /// `key`: the key, hashed first if it was longer than a block.
            key: [u8; $block],
            /// `key_len`: bytes of `key` in use, at most a block.
            key_len: usize,
        }

        impl Default for $ctx_ty {
            fn default() -> Self {
                Self {
                    ctx: <$hash_ctx>::default(),
                    key: [0; $block],
                    key_len: 0,
                }
            }
        }

        impl $ctx_ty {
            #[doc = concat!("`", $name, "`'s `Init`: starts an HMAC under `key`.")]
            pub fn new(key: &[u8]) -> Self {
                let mut this = Self::default();
                let mut k_ipad = [0u8; $block];

                if key.len() > $block {
                    let mut hash = <$hash_ctx>::new();
                    hash.update(key);
                    let mut hashed = hash.finalize();
                    this.key[..$digest].copy_from_slice(&hashed);
                    this.key_len = $digest;
                    explicit_bzero(&mut hashed);
                } else {
                    this.key[..key.len()].copy_from_slice(key);
                    this.key_len = key.len();
                }

                k_ipad[..this.key_len].copy_from_slice(&this.key[..this.key_len]);
                for b in k_ipad.iter_mut() {
                    *b ^= 0x36;
                }

                this.ctx = <$hash_ctx>::new();
                this.ctx.update(&k_ipad);

                explicit_bzero(&mut k_ipad);
                this
            }

            #[doc = concat!("`", $name, "`'s `Update`: adds `data` to the message.")]
            pub fn update(&mut self, data: &[u8]) {
                self.ctx.update(data);
            }

            #[doc = concat!("`", $name, "`'s `Final`: the MAC of the message; the context is wiped.")]
            pub fn finalize(&mut self) -> [u8; $digest] {
                let mut k_opad = [0u8; $block];

                let mut inner = self.ctx.finalize();

                k_opad[..self.key_len].copy_from_slice(&self.key[..self.key_len]);
                for b in k_opad.iter_mut() {
                    *b ^= 0x5c;
                }

                self.ctx = <$hash_ctx>::new();
                self.ctx.update(&k_opad);
                self.ctx.update(&inner);
                let digest = self.ctx.finalize();

                explicit_bzero(&mut k_opad);
                explicit_bzero(&mut inner);
                wipe(self);
                digest
            }
        }
    };
}

hmac_family!(
    HmacMd5Ctx,
    Md5Ctx,
    MD5_BLOCK_LENGTH,
    MD5_DIGEST_LENGTH,
    "HMAC_MD5_CTX"
);

hmac_family!(
    HmacSha1Ctx,
    Sha1Ctx,
    SHA1_BLOCK_LENGTH,
    SHA1_DIGEST_LENGTH,
    "HMAC_SHA1_CTX"
);

hmac_family!(
    HmacSha256Ctx,
    Sha256Ctx,
    SHA256_BLOCK_LENGTH,
    SHA256_DIGEST_LENGTH,
    "HMAC_SHA256_CTX"
);
