//! Symmetric Toeplitz hashing: `<net/toeplitz.h>` and `net/toeplitz.c`.
//!
//! Upstream: sys/net/toeplitz.h @ 3ce1f3f79392
//! Upstream: sys/net/toeplitz.c @ 3ce1f3f79392
//!
//! The Toeplitz hash of a 16-bit number, considered as a column vector over the field with two
//! elements, is a matrix multiplication with a 16x16 circulant Toeplitz matrix generated by a
//! 16-bit key. The hash is linear, so the hash of `a ^ b` is the hash of `a` xor the hash of
//! `b`, and a flow's addresses and ports are xor-ed together before hashing: both directions
//! of a flow hash to the same value (hence "symmetric"). The matrix is invertible exactly when
//! the key has odd parity, and the system key is drawn as such.
//!
//! [`StoeplitzCache`] holds the products of the key's first eight columns with every byte
//! value, so a 16-bit hash is two table lookups. The system cache, [`stoeplitz_cache`], is
//! filled by [`stoeplitz_init`] from `main()` and serves `pf`'s state hashing and the
//! receive-side scaling keys that drivers program into hardware ([`stoeplitz_to_key`]).
//!
//! Status: `toeplitz.h` `ported`, `toeplitz.c` `ported`.
//!
//! ## Deviations
//! - `const struct stoeplitz_cache *const stoeplitz_cache` (a pointer to the static
//!   `stoeplitz_syskey_cache`) is the function [`stoeplitz_cache`], returning
//!   `&'static StoeplitzCache` from a `StaticCell` that only [`stoeplitz_init`] writes, once,
//!   from `main()` on the boot CPU before any reader exists. `stoeplitz_keyseed` is an
//!   `AtomicU16`, under its C name (`docs/C_TO_RUST.md`: a global beside an uppercase constant
//!   of the same spelling, `STOEPLITZ_KEYSEED`).
//! - The macros `stoeplitz_n16(n)`, `stoeplitz_n32(n)`, `stoeplitz_h16(h)`,
//!   `stoeplitz_h32(h)`, `stoeplitz_h64(h)`, `stoeplitz_port(p)`, `stoeplitz_ip4(...)`,
//!   `stoeplitz_ip4port(...)`, `stoeplitz_ip6(...)`, `stoeplitz_ip6port(...)` and
//!   `stoeplitz_eaddr(ea)` are functions of the same names over the system cache.
//! - `stoeplitz_hash_ip6`, `stoeplitz_hash_ip6port` and their macros (C `#ifdef INET6`) are
//!   always compiled, not gated by the `inet6` feature: `sys/netinet6` compiles
//!   unconditionally and `in6_pcb.c`'s `in6_pcb_newflow` calls `stoeplitz_ip6port`. They take
//!   the sixteen bytes of each `struct in6_addr` (`&[u8; 16]`, the callers pass `s6_addr`);
//!   `s6_addr32[i]` is the native-order word at byte `4 * i`, as the C's union reads it.
//! - `stoeplitz_to_key(void *key, size_t klen)` takes `&mut [u8]`; its `KASSERT` is
//!   `kassert!`. `stoeplitz_hash_eaddr` takes `&[u8; 6]` and reads the C's `uint16_t *` view as
//!   native-order words.
//! - `stoeplitz_cache_init` computes the columns `skey << b | skey >> (NBSK - b)` as
//!   `skey.rotate_left(b)`: the C's shift by 16 for `b == 0` is defined only because `skey` is
//!   promoted to `int`, and the expression is a 16-bit rotation.
//! - `stoeplitz_hash_h16` keeps the C's two byte-order variants, chosen by
//!   `BYTE_ORDER == BIG_ENDIAN` (a constant, so the other arm compiles away).

use core::sync::atomic::{AtomicU16, Ordering};

use libkern::StaticCell;

use crate::dev::rnd::arc4random;
use crate::kassert;
use crate::sys::endian::{BIG_ENDIAN, BYTE_ORDER, htons, swap16};

/// `STOEPLITZ_KEYSEED`: the system key before [`stoeplitz_init`] draws a random one.
pub const STOEPLITZ_KEYSEED: StoeplitzKey = 0x6d5a;

/// `NBBY`: bits in a byte (`<sys/select.h>`'s, here for the cache's eight columns).
const NBBY: u32 = u8::BITS;

/// `stoeplitz_key`: the 16-bit key that generates the Toeplitz matrix.
pub type StoeplitzKey = u16;

/// `struct stoeplitz_cache`: the products of the key's first eight matrix columns with every
/// byte value.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct StoeplitzCache {
    /// `H * val` for each byte `val`.
    pub bytes: [u16; 256],
}

impl StoeplitzCache {
    /// An all-zero cache, as the C's static is before `stoeplitz_cache_init`.
    pub const fn new() -> Self {
        Self { bytes: [0; 256] }
    }
}

impl Default for StoeplitzCache {
    fn default() -> Self {
        Self::new()
    }
}

/// `stoeplitz_keyseed`: the system key, [`STOEPLITZ_KEYSEED`] until [`stoeplitz_init`].
#[allow(non_upper_case_globals)] // the C name; `STOEPLITZ_KEYSEED` is the constant
static stoeplitz_keyseed: AtomicU16 = AtomicU16::new(STOEPLITZ_KEYSEED);

/// `stoeplitz_syskey_cache`: the cache of the system key. Written only by [`stoeplitz_init`],
/// once, from `main()` on the boot CPU before any reader; read through [`stoeplitz_cache`].
static STOEPLITZ_SYSKEY_CACHE: StaticCell<StoeplitzCache> = StaticCell::new(StoeplitzCache::new());

/// `stoeplitz_cache_entry`: `H * byte`.
#[inline]
pub const fn stoeplitz_cache_entry(scache: &StoeplitzCache, byte: u8) -> u16 {
    scache.bytes[byte as usize]
}

/// `stoeplitz_hash_n16`: hashes a `u16` in network byte order.
#[inline]
pub const fn stoeplitz_hash_n16(scache: &StoeplitzCache, n16: u16) -> u16 {
    let hi = stoeplitz_cache_entry(scache, (n16 >> 8) as u8);
    let lo = stoeplitz_cache_entry(scache, n16 as u8);
    hi ^ swap16(lo)
}

/// `stoeplitz_hash_n32`: hashes a `u32` in network byte order (its two halves xor-ed).
#[inline]
pub const fn stoeplitz_hash_n32(scache: &StoeplitzCache, n32: u32) -> u16 {
    stoeplitz_hash_n16(scache, (n32 ^ (n32 >> 16)) as u16)
}

/// `stoeplitz_hash_h16`: hashes a `u16` in host byte order; the result is that of
/// [`stoeplitz_hash_n16`] on the value in network order.
#[inline]
pub const fn stoeplitz_hash_h16(scache: &StoeplitzCache, h16: u16) -> u16 {
    let lo = stoeplitz_cache_entry(scache, h16 as u8);
    let hi = stoeplitz_cache_entry(scache, (h16 >> 8) as u8);
    if BYTE_ORDER == BIG_ENDIAN {
        hi ^ swap16(lo)
    } else {
        swap16(hi) ^ lo
    }
}

/// `stoeplitz_hash_h32`: hashes a `u32` in host byte order.
#[inline]
pub const fn stoeplitz_hash_h32(scache: &StoeplitzCache, h32: u32) -> u16 {
    stoeplitz_hash_h16(scache, (h32 ^ (h32 >> 16)) as u16)
}

/// `stoeplitz_hash_h64`: hashes a `u64` in host byte order.
#[inline]
pub const fn stoeplitz_hash_h64(scache: &StoeplitzCache, h64: u64) -> u16 {
    stoeplitz_hash_h32(scache, (h64 ^ (h64 >> 32)) as u32)
}

/// `stoeplitz_cache`: the system cache, filled by [`stoeplitz_init`] at boot (all zeroes, so
/// every hash 0, before).
#[inline]
pub fn stoeplitz_cache() -> &'static StoeplitzCache {
    // SAFETY: the only `&mut` to the cell is taken by `stoeplitz_init`, which `main()` calls
    // once on the boot CPU before sockets, pf or any driver exist to call here.
    unsafe { STOEPLITZ_SYSKEY_CACHE.get() }
}

/// `stoeplitz_n16(n16)`: [`stoeplitz_hash_n16`] with the system cache.
#[inline]
pub fn stoeplitz_n16(n16: u16) -> u16 {
    stoeplitz_hash_n16(stoeplitz_cache(), n16)
}

/// `stoeplitz_n32(n32)`: [`stoeplitz_hash_n32`] with the system cache.
#[inline]
pub fn stoeplitz_n32(n32: u32) -> u16 {
    stoeplitz_hash_n32(stoeplitz_cache(), n32)
}

/// `stoeplitz_h16(h16)`: [`stoeplitz_hash_h16`] with the system cache.
#[inline]
pub fn stoeplitz_h16(h16: u16) -> u16 {
    stoeplitz_hash_h16(stoeplitz_cache(), h16)
}

/// `stoeplitz_h32(h32)`: [`stoeplitz_hash_h32`] with the system cache.
#[inline]
pub fn stoeplitz_h32(h32: u32) -> u16 {
    stoeplitz_hash_h32(stoeplitz_cache(), h32)
}

/// `stoeplitz_h64(h64)`: [`stoeplitz_hash_h64`] with the system cache.
#[inline]
pub fn stoeplitz_h64(h64: u64) -> u16 {
    stoeplitz_hash_h64(stoeplitz_cache(), h64)
}

/// `stoeplitz_port(p)`: hashes a port in network byte order.
#[inline]
pub fn stoeplitz_port(p: u16) -> u16 {
    stoeplitz_n16(p)
}

