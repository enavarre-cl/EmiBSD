/// `parity`: the count (mod 2) of ones in the binary representation of `n16`.
pub fn parity(n16: u16) -> i32 {
    let mut n16 = n16;
    n16 = ((n16 & 0xaaaa) >> 1) ^ (n16 & 0x5555);
    n16 = ((n16 & 0xcccc) >> 2) ^ (n16 & 0x3333);
    n16 = ((n16 & 0xf0f0) >> 4) ^ (n16 & 0x0f0f);
    n16 = ((n16 & 0xff00) >> 8) ^ (n16 & 0x00ff);
    i32::from(n16)
}

/// `stoeplitz_random_seed`: a key drawn uniformly at random among those of parity 1, the ones
/// whose Toeplitz matrix is invertible.
pub fn stoeplitz_random_seed() -> StoeplitzKey {
    let mut seed = (arc4random() & u32::from(u16::MAX)) as StoeplitzKey;
    if parity(seed) == 0 {
        seed ^= 1;
    }
    seed
}

/// `stoeplitz_init`: draws the system key and fills the system cache. Called once, from
/// `main()`, on the boot CPU.
pub fn stoeplitz_init() {
    let seed = stoeplitz_random_seed();
    stoeplitz_keyseed.store(seed, Ordering::Relaxed);
    // SAFETY: `main()` calls this once on the boot CPU before anything that reads the cache
    // (`stoeplitz_cache`) exists, so no other reference to it is live.
    stoeplitz_cache_init(unsafe { STOEPLITZ_SYSKEY_CACHE.get_mut() }, seed);
}

/// `stoeplitz_cache_init`: fills `scache` for the key `skey`.
///
/// The first eight columns H of the Toeplitz matrix T generate the remaining eight with the
/// byteswap J = `swap16`: T = [H JH]. Thus the hash of n = [hi lo] is
/// (H * hi) ^ swap16(H * lo), and H * val is cached for every byte value.
pub fn stoeplitz_cache_init(scache: &mut StoeplitzCache, skey: StoeplitzKey) {
    // Calculate the first eight columns H of the Toeplitz matrix T.
    let mut column = [0u16; NBBY as usize];
    for (b, col) in (0..NBBY).zip(column.iter_mut()) {
        // skey << b | skey >> (NBSK - b), in 16 bits.
        *col = skey.rotate_left(b);
    }

    // Cache the results of H * val for all possible values of a byte.
    for (val, entry) in scache.bytes.iter_mut().enumerate() {
        let mut res = 0u16;
        for (b, col) in (0..NBBY).zip(column.iter()) {
            let shift = NBBY - b - 1;
            if val & (1 << shift) != 0 {
                res ^= *col;
            }
        }
        *entry = res;
    }
}

/// `stoeplitz_hash_ip4`: hashes an IPv4 address pair (`in_addr_t`, network order); symmetric
/// in the two addresses.
pub fn stoeplitz_hash_ip4(scache: &StoeplitzCache, faddr: u32, laddr: u32) -> u16 {
    stoeplitz_hash_n32(scache, faddr ^ laddr)
}

/// `stoeplitz_hash_ip4port`: hashes an IPv4 address and port pair (network order); the same
/// for both directions of a flow.
pub fn stoeplitz_hash_ip4port(
    scache: &StoeplitzCache,
    faddr: u32,
    laddr: u32,
    fport: u16,
    lport: u16,
) -> u16 {
    stoeplitz_hash_n32(scache, faddr ^ laddr ^ u32::from(fport) ^ u32::from(lport))
}

/// The xor of the eight `s6_addr32` words of two IPv6 addresses.
fn in6_xor(faddr6: &[u8; 16], laddr6: &[u8; 16]) -> u32 {
    let word = |a: &[u8; 16], i: usize| u32::from_ne_bytes([a[i], a[i + 1], a[i + 2], a[i + 3]]);
    (0..16)
        .step_by(4)
        .fold(0, |n32, i| n32 ^ word(faddr6, i) ^ word(laddr6, i))
}

/// `stoeplitz_hash_ip6`: hashes an IPv6 address pair (the bytes of each `struct in6_addr`).
pub fn stoeplitz_hash_ip6(scache: &StoeplitzCache, faddr6: &[u8; 16], laddr6: &[u8; 16]) -> u16 {
    stoeplitz_hash_n32(scache, in6_xor(faddr6, laddr6))
}

/// `stoeplitz_hash_ip6port`: hashes an IPv6 address and port pair (network order).
pub fn stoeplitz_hash_ip6port(
    scache: &StoeplitzCache,
    faddr6: &[u8; 16],
    laddr6: &[u8; 16],
    fport: u16,
    lport: u16,
) -> u16 {
    let n32 = in6_xor(faddr6, laddr6) ^ u32::from(fport) ^ u32::from(lport);
    stoeplitz_hash_n32(scache, n32)
}

/// `stoeplitz_hash_eaddr`: hashes an Ethernet address.
pub fn stoeplitz_hash_eaddr(scache: &StoeplitzCache, ea: &[u8; 6]) -> u16 {
    let ea16 = |i: usize| u16::from_ne_bytes([ea[2 * i], ea[2 * i + 1]]);
    stoeplitz_hash_n16(scache, ea16(0) ^ ea16(1) ^ ea16(2))
}

/// `stoeplitz_to_key`: fills `key` (an even number of bytes) with the system key, for a
/// driver's receive-side scaling hash key.
pub fn stoeplitz_to_key(key: &mut [u8]) {
    let skey = htons(stoeplitz_keyseed.load(Ordering::Relaxed));

    kassert!(key.len().is_multiple_of(2));

    for k in key.as_chunks_mut::<2>().0 {
        *k = [(skey >> 8) as u8, skey as u8];
    }
}

