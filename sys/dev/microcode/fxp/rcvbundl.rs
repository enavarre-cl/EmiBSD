//! `<dev/microcode/fxp/rcvbundl.h>`: Intel's receive bundling ("CPUSaver") microcode for the
//! 82558 and later controllers (D101 A and B steps, D101M, D101S, D102 B, C and E steps).
//!
//! Upstream: sys/dev/microcode/fxp/rcvbundl.h @ 3ce1f3f79392
//!
//! Each array is the microcode of one controller and is incompatible with any other. The
//! `*_DWORD` constants are the dword indexes of the instructions whose low 16-bit literal the
//! driver patches before the download: the dead-man timer (`CPUSAVER_DWORD`), the maximum
//! bundle (`CPUSAVER_BUNDLE_MAX_DWORD`) and the minimum size mask (`CPUSAVER_MIN_SIZE_DWORD`)
//! (the header's long comment describes them). OpenBSD's `build.c` includes the arrays to
//! write the `/etc/firmware/fxp-*` files and `fxp_load_ucode` reads those with
//! `loadfirmware(9)`; the kernel uses the `*_DWORD` indexes only. Here `cargo xtask userland`
//! writes the files (`tools/xtask/src/userland/firmware.rs`, `build.c` re-expressed) from
//! the C header, and the arrays are kept in the crate so that a host test can cross-check
//! them against the header and against the generated files.
//!
//! ## Deviations
//! - The `#define`s of the arrays are `const` arrays of `u32`, one value per C initialiser,
//!   with the same names; `FXP_FIRMWARE` lists the seven that `build.c` writes, with their
//!   file names. The header's prose comments (the CPUSaver parameters, the per-controller
//!   version notes) are not repeated except where they say what an array is.

